    #[test]
    fn inline_parsing() {
        let html = "<!doctype html><html><head>\r\n\
            <!-- <script>commented()</script> -->\
            <script type=module src=\"/a.js\"></script>\
            <SCRIPT>a()\r\n</SCRIPT >\
            <script id='x' data-a=\"b>c\">b()</script>\
            <style>p{}</style>\
            <p style=\"color: red\" title=x></p><br/>\
            <i style='a:&quot;b&quot;'></i><b style=unquoted>x</b>";
        let found = web_build::inline(html);
        assert_eq!(found.scripts, ["a()\n", "b()"]);
        assert_eq!(found.styles, ["p{}"]);
        assert_eq!(found.style_attrs, ["color: red", "a:\"b\"", "unquoted"]);
        assert!(found.handlers.is_empty());
        assert!(web_build::csp("<a onclick=\"x()\">", &[]).is_err());
        assert!(web_build::csp("<body onload=x>", &[]).is_err());
        // Unterminated input doesn't panic.
        for cut in ["<script>x", "<p style=\"x", "<!-- x", "<", "<a b='"] {
            web_build::inline(cut);
        }
    }

