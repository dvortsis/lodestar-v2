    #[test]
    fn fixture_csp_hashes_the_inline_scripts() {
        let bundle = fixture();
        assert!(bundle.built);
        let index = bundle
            .files
            .iter()
            .find(|f| f.path == "index.html")
            .unwrap();
        let csp = index.csp.as_deref().unwrap();
        // `openssl dgst -sha256 -binary | base64` over the text of the
        // fixture's two inline scripts (the theme pre-paint script and
        // SvelteKit's bootstrap), computed independently of this code.
        assert!(csp.contains("script-src 'self' 'sha256-"), "{csp}");
        for hash in [
            "'sha256-8sGxyFFW7xk/8Me2rukbUx/2+xX3j3SVt7SC1hk3xU8='",
            "'sha256-dFiWWMzomUn+/stkWvnvD1vdjHgBbOt4pEa5d0RvHMg='",
        ] {
            assert!(csp.contains(hash), "{csp} lacks {hash}");
        }
        // SvelteKit's `<div style="display: contents">`.
        assert!(
            csp.contains(&format!(
                "style-src-attr 'unsafe-hashes' {}",
                web_build::hash_source("display: contents")
            )),
            "{csp}"
        );
        assert!(csp.contains("style-src 'self'; "), "{csp}");
        // The fixture chunk's static template style, deduplicated.
        assert!(
            csp.contains(&web_build::hash_source("position: absolute; width: 1px")),
            "{csp}"
        );
        // The external module script and the commented-out one aren't
        // hashed, nor the chunk's interpolated style.
        assert_eq!(csp.matches("'sha256-").count(), 4, "{csp}");
    }

