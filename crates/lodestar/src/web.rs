    fn app() -> Router {
        Router::new()
            .route("/metrics", get(|| async { "metrics" }))
            .route("/healthz", get(|| async { "ok" }))
            .route("/status", get(|| async { "status" }))
            .route("/api/status", get(|| async { "api status" }))
            .nest(
                "/api/v1",
                Router::new()
                    .route("/auth", get(|| async { "auth" }))
                    .fallback(lodestar_api::error::no_route),
            )
            .fallback(serve)
    }

    async fn call(method: &str, uri: &str, headers: &[(&str, &str)]) -> Response {
        let mut req = Request::builder().method(method).uri(uri);
        for (k, v) in headers {
            req = req.header(*k, *v);
        }
        app()
            .oneshot(req.body(Body::empty()).unwrap())
            .await
            .unwrap()
    }

    async fn body(res: Response) -> Vec<u8> {
        to_bytes(res.into_body(), usize::MAX)
            .await
            .unwrap()
            .to_vec()
    }

