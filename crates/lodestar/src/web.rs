    #[tokio::test]
    async fn negotiates_the_encoding() {
        let asset = index();
        let (br, gz) = (asset.br.is_some(), asset.gz.is_some());
        let cases: &[(&str, Option<&str>)] = &[
            ("", None),
            ("identity", None),
            ("gzip", gz.then_some("gzip")),
            (
                "gzip, deflate, br, zstd",
                if br { Some("br") } else { gz.then_some("gzip") },
            ),
            (
                "br;q=0.5, gzip",
                if gz { Some("gzip") } else { br.then_some("br") },
            ),
            ("br;q=0, gzip;q=0", None),
            ("*", if br { Some("br") } else { gz.then_some("gzip") }),
            ("*;q=0", None),
            ("BR", br.then_some("br")),
            // A malformed q drops the item.
            ("br;q=2", None),
        ];
        for (accept, want) in cases {
            let res = call("GET", "/", &[("accept-encoding", accept)]).await;
            assert_eq!(header(&res, "content-encoding"), *want, "{accept:?}");
            if br || gz {
                assert_eq!(header(&res, "vary"), Some("Accept-Encoding"));
            }
            let bytes = body(res).await;
            let decoded = match want {
                Some("br") => web_build::unbrotli(&bytes).unwrap(),
                Some(_) => {
                    let mut out = Vec::new();
                    std::io::Read::read_to_end(
                        &mut flate2::read::GzDecoder::new(&bytes[..]),
                        &mut out,
                    )
                    .unwrap();
                    out
                }
                None => bytes,
            };
            assert_eq!(decoded, asset.raw, "{accept:?}");
        }
    }

