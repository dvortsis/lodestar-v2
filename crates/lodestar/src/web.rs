//! Serves the embedded Svelte UI (architecture §10.1, §12): the router's
//! fallback, so every route it declares (`/api/**`, `/metrics`,
//! `/healthz`, `/status`) wins over it.
//!
//! - **Caching by class:** `_app/immutable/**` has content-hashed names and
//!   is cached for a year; HTML and `_app/version.json` revalidate every
//!   time (`no-cache` + ETag); everything else (`/brand`, `/fonts`,
//!   `/themes.json`) keeps its name across builds, so an hour + ETag.
//! - **Encoding:** brotli or gzip bodies precompressed at build time,
//!   chosen by `Accept-Encoding`, with `Vary: Accept-Encoding`.
//! - **SPA fallback:** an unknown GET path gets `index.html`, except under
//!   `/api/` (the API's 404 envelope) and the asset directories (a plain
//!   404, so a stale chunk fails loudly rather than parsing HTML).
//! - **No filesystem:** paths are looked up in a table built at compile
//!   time, so there is nothing to list or traverse; `.`/`..` segments,
//!   empty segments and backslashes, raw or percent-encoded, are 404s.

use axum::body::Body;
use axum::http::{HeaderMap, HeaderValue, Method, StatusCode, Uri, header};
use axum::response::{IntoResponse, Response};

/// One embedded file (generated by `build.rs`; see `web_build.rs`).
#[derive(Debug)]
pub struct Asset {
    pub path: &'static str,
    pub mime: &'static str,
    pub etag: &'static str,
    pub csp: Option<&'static str>,
    pub raw: &'static [u8],
    pub br: Option<&'static [u8]>,
    pub gz: Option<&'static [u8]>,
}

mod embedded {
    use super::Asset;
    include!(concat!(env!("OUT_DIR"), "/web_assets.rs"));
}

const IMMUTABLE: &str = "public, max-age=31536000, immutable";
const SHORT: &str = "public, max-age=3600";
const REVALIDATE: &str = "no-cache";
const PERMISSIONS: &str = "accelerometer=(), camera=(), display-capture=(), geolocation=(), \
     gyroscope=(), magnetometer=(), microphone=(), midi=(), payment=(), usb=()";
/// Paths that hold only files: a miss there is a 404, never the app.
const ASSET_DIRS: [&str; 3] = ["_app/", "fonts/", "brand/"];

/// Whether a real UI build is embedded (false: the stub page).
#[cfg_attr(not(test), allow(dead_code))]
pub const BUILT: bool = embedded::BUILT;

fn find(path: &str) -> Option<&'static Asset> {
    embedded::ASSETS
        .binary_search_by(|a| a.path.cmp(path))
        .ok()
        .map(|i| &embedded::ASSETS[i])
}

fn index() -> &'static Asset {
    find("index.html").expect("the bundle always has index.html")
}

/// The router fallback.
pub async fn serve(method: Method, uri: Uri, headers: HeaderMap) -> Response {
    let raw = uri.path();
    let key = key(raw);
    let api = |p: &str| p == "api" || p.starts_with("api/");
    if api(raw.trim_start_matches('/')) || key.as_deref().is_some_and(api) {
        return lodestar_api::error::no_route().await.into_response();
    }
    if method != Method::GET && method != Method::HEAD {
        let mut res = plain(StatusCode::METHOD_NOT_ALLOWED, "Method not allowed\n");
        res.headers_mut()
            .insert(header::ALLOW, HeaderValue::from_static("GET, HEAD"));
        return res;
    }
    let Some(key) = key else {
        return plain(StatusCode::NOT_FOUND, "Not found\n");
    };
    let key = if key.is_empty() { "index.html" } else { &key };
    let asset = match find(key) {
        Some(a) => a,
        None if key == "themes.json" || ASSET_DIRS.iter().any(|d| key.starts_with(d)) => {
            return plain(StatusCode::NOT_FOUND, "Not found\n");
        }
        None => index(),
    };
    respond(asset, &headers)
}

/// The table key for a request path: percent-decoded, without the leading
/// slash. `None` for anything that isn't a plain relative path.
fn key(path: &str) -> Option<String> {
    let rest = path.strip_prefix('/')?;
    let bytes = rest.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%' {
            let hex = std::str::from_utf8(bytes.get(i + 1..i + 3)?).ok()?;
            out.push(u8::from_str_radix(hex, 16).ok()?);
            i += 3;
        } else {
            out.push(bytes[i]);
            i += 1;
        }
    }
    let key = String::from_utf8(out).ok()?;
    if key.is_empty() {
        return Some(key);
    }
    // A trailing slash is allowed (`/search/`); any other empty segment,
    // dot segment, backslash or control character is not.
    let segments = key.strip_suffix('/').unwrap_or(&key);
    let bad = segments
        .split('/')
        .any(|s| s.is_empty() || s == "." || s == "..")
        || key.chars().any(|c| c == '\\' || c.is_control());
    (!bad).then_some(key)
}

fn respond(asset: &'static Asset, req: &HeaderMap) -> Response {
    let (body, encoding) = match pick(req, asset.br.is_some(), asset.gz.is_some()) {
        Some("br") => (asset.br.unwrap(), Some("br")),
        Some(_) => (asset.gz.unwrap(), Some("gzip")),
        None => (asset.raw, None),
    };
    let etag = match encoding {
        // A strong ETag names one representation.
        Some(enc) => format!("{}-{enc}\"", asset.etag.trim_end_matches('"')),
        None => asset.etag.to_string(),
    };
    let fresh = req
        .get_all(header::IF_NONE_MATCH)
        .iter()
        .filter_map(|v| v.to_str().ok())
        .flat_map(|v| v.split(','))
        .map(|t| t.trim().trim_start_matches("W/"))
        .any(|t| t == "*" || t == etag);

    let mut res = if fresh {
        Response::builder()
            .status(StatusCode::NOT_MODIFIED)
            .body(Body::empty())
    } else {
        Response::builder()
            .header(header::CONTENT_TYPE, asset.mime)
            .body(Body::from(body))
    }
    .expect("static headers are valid");
    let h = res.headers_mut();
    h.insert(
        header::CACHE_CONTROL,
        HeaderValue::from_static(cache(asset)),
    );
    h.insert(header::ETAG, HeaderValue::try_from(etag).expect("hex ETag"));
    if asset.br.is_some() || asset.gz.is_some() {
        h.insert(header::VARY, HeaderValue::from_static("Accept-Encoding"));
    }
    if let (Some(enc), false) = (encoding, fresh) {
        h.insert(header::CONTENT_ENCODING, HeaderValue::from_static(enc));
    }
    h.insert(
        header::X_CONTENT_TYPE_OPTIONS,
        HeaderValue::from_static("nosniff"),
    );
    if let (Some(csp), false) = (asset.csp, fresh) {
        h.insert(
            header::CONTENT_SECURITY_POLICY,
            HeaderValue::from_static(csp),
        );
        h.insert(
            header::REFERRER_POLICY,
            HeaderValue::from_static("no-referrer"),
        );
        h.insert("permissions-policy", HeaderValue::from_static(PERMISSIONS));
    }
    res
}

fn cache(asset: &Asset) -> &'static str {
    if asset.path.starts_with("_app/immutable/") {
        IMMUTABLE
    } else if asset.csp.is_some() || asset.path == "_app/version.json" {
        // SvelteKit polls version.json to notice a new deployment.
        REVALIDATE
    } else {
        SHORT
    }
}

/// The best encoding the client accepts that we have: the highest q,
/// brotli on a tie. `None` means identity.
fn pick(req: &HeaderMap, br: bool, gz: bool) -> Option<&'static str> {
    // Thousandths; `None` = not mentioned.
    let (mut q_br, mut q_gz, mut q_any) = (None, None, None);
    for value in req.get_all(header::ACCEPT_ENCODING) {
        let Ok(value) = value.to_str() else { continue };
        for item in value.split(',') {
            let mut parts = item.split(';');
            let coding = parts.next().unwrap_or("").trim().to_ascii_lowercase();
            let q = parts
                .filter_map(|p| p.trim().strip_prefix("q="))
                .next()
                .map_or(Some(1000), qvalue);
            let Some(q) = q else { continue };
            match coding.as_str() {
                "br" => q_br = Some(q),
                "gzip" | "x-gzip" => q_gz = Some(q),
                "*" => q_any = Some(q),
                _ => {}
            }
        }
    }
    let q_br = if br { q_br.or(q_any).unwrap_or(0) } else { 0 };
    let q_gz = if gz { q_gz.or(q_any).unwrap_or(0) } else { 0 };
    if q_br > 0 && q_br >= q_gz {
        Some("br")
    } else if q_gz > 0 {
        Some("gzip")
    } else {
        None
    }
}

/// An RFC 9110 qvalue in thousandths; `None` if malformed.
fn qvalue(s: &str) -> Option<u16> {
    let s = s.trim();
    let (int, frac) = s.split_once('.').unwrap_or((s, ""));
    if frac.len() > 3 || !frac.bytes().all(|b| b.is_ascii_digit()) {
        return None;
    }
    let frac: u16 = format!("{frac:0<3}").parse().ok()?;
    match int {
        "0" => Some(frac),
        "1" if frac == 0 => Some(1000),
        _ => None,
    }
}

fn plain(status: StatusCode, body: &'static str) -> Response {
    (
        status,
        [
            (header::CONTENT_TYPE, "text/plain; charset=utf-8"),
            (header::X_CONTENT_TYPE_OPTIONS, "nosniff"),
        ],
        body,
    )
        .into_response()
}

