// Writes `message-maps/<id>.ts` (one per settings section, plus `group` for the group headings)
// and `message-map.ts` (the loaders): every server message of `features/settings/messages/en.json`,
// each read statically from `m` so the bundle keeps exactly these (Paraglide's Vite plugin
// compiles one module per locale, so a glob over per-message files finds nothing in a build).
// A section's map loads with its form (`loadMessages`), so the engine chunk carries none of them.
//
//   node --experimental-strip-types src/lib/features/settings/form/message-map.gen.ts
//
// `message-map.test.ts` fails when the file is out of date.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const HERE = import.meta.dirname;
export const MAP_FILE = join(HERE, 'message-map.ts');
export const MAPS_DIR = join(HERE, 'message-maps');
export const EN_FILE = join(HERE, '../messages/en.json');

/**
 * Keys the server can name: `settings_*` messages without placeholders (label, help and group
 * keys never take any). The engine's own `settings_form_*` strings and a screen's own `settings_screen_*` strings are
 * never server keys.
 */
export function messageKeys(text: string): string[] {
	return Object.entries(JSON.parse(text) as Record<string, unknown>)
		.filter(
			([k, v]) =>
				k.startsWith('settings_') &&
				!k.startsWith('settings_form_') &&
				!k.startsWith('settings_screen_') &&
				typeof v === 'string' &&
				!v.includes('{')
		)
		.map(([k]) => k)
		.sort();
}

/** The map a key belongs to: its section (`settings_<section>_…`), or `group` for headings. */
export function mapId(key: string): string {
	return key.split('_')[1]!;
}

/** The keys of each map, by map id. */
export function groupKeys(keys: string[]): Record<string, string[]> {
	const out: Record<string, string[]> = {};
	for (const k of keys) (out[mapId(k)] ??= []).push(k);
	return out;
}

const TAB = 2;
const WIDTH = 100;

export function renderMap(keys: string[]): string {
	// Laid out as prettier would (tabs, no trailing comma), so `npm run check` passes as written.
	// An entry that would pass the print width breaks after the colon, as prettier does.
	const entry = (k: string, last: boolean) =>
		TAB + `${k}: m.${k}`.length + (last ? 0 : 1) > WIDTH ? `\t${k}:\n\t\tm.${k}` : `\t${k}: m.${k}`;
	const body = keys.length
		? `{\n${keys.map((k, i) => entry(k, i === keys.length - 1)).join(',\n')}\n}`
		: '{}';
	return [
		'// Generated by ../message-map.gen.ts from ../../messages/en.json; do not edit.',
		...(keys.length ? ["import { m } from '$lib/paraglide/messages.js';", ''] : ['']),
		`export const MESSAGES: Record<string, () => string> = ${body};`,
		''
	].join('\n');
}

/** `message-map.ts`: how to load each map. It names no message, so it stays in the engine. */
export function renderLoaders(ids: string[]): string {
	return [
		'// Generated by message-map.gen.ts from ../messages/en.json; do not edit.',
		'',
		'export const LOADERS: Record<string, () => Promise<{ MESSAGES: Record<string, () => string> }>> = {',
		ids.map((id) => `\t${id}: () => import('./message-maps/${id}')`).join(',\n'),
		'};',
		''
	].join('\n');
}

/** Every generated file: its path and content. */
export function render(text: string): Record<string, string> {
	const by = groupKeys(messageKeys(text));
	const ids = Object.keys(by).sort();
	return {
		[MAP_FILE]: renderLoaders(ids),
		...Object.fromEntries(ids.map((id) => [join(MAPS_DIR, `${id}.ts`), renderMap(by[id]!)]))
	};
}

if (process.argv[1] === import.meta.filename) {
	const files = render(readFileSync(EN_FILE, 'utf8'));
	mkdirSync(MAPS_DIR, { recursive: true });
	for (const f of readdirSync(MAPS_DIR)) rmSync(join(MAPS_DIR, f));
	for (const [file, content] of Object.entries(files)) writeFileSync(file, content);
}
