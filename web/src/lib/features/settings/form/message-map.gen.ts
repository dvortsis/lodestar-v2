// Writes the message map: every server message of `features/settings/messages/en.json`, each read
// statically from `m` so the bundle keeps exactly these (Paraglide's Vite plugin compiles one
// module per locale, so a glob over per-message files finds nothing in a build). The messages
// are split by section: `message-map.ts` lists a loader per unit and `message-map/<unit>.ts`
// holds that unit's messages, so a screen loads only its own sections' text
// (`loadSettingMessages` in `messages.ts`). `common` holds what every screen and the Overview
// need: the group headings and each section's label and help.
//
//   node --experimental-strip-types src/lib/features/settings/form/message-map.gen.ts
//
// `messages.test.ts` fails when the files are out of date. The output is formatted with the
// layout Prettier would give them (tabs, no trailing comma, a property over the print width wrapped
// after its colon), so `prettier --check .` passes as written.
import { readFileSync, rmSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const HERE = import.meta.dirname;
export const MAP_FILE = join(HERE, 'message-map.ts');
export const MAP_DIR = join(HERE, 'message-map');
export const EN_FILE = join(HERE, '../messages/en.json');

/** The unit for messages every section uses (the group headings). */
export const COMMON = 'common';

/**
 * Keys the server can name: `settings_*` messages without placeholders (label, help and group
 * keys never take any). The engine's own `settings_form_*` strings and the screens' `settings_ui_*`
 * strings are never server keys.
 */
export function messageKeys(text: string): string[] {
	return Object.entries(JSON.parse(text) as Record<string, unknown>)
		.filter(
			([k, v]) =>
				k.startsWith('settings_') &&
				!k.startsWith('settings_form_') &&
				!k.startsWith('settings_ui_') &&
				typeof v === 'string' &&
				!v.includes('{')
		)
		.map(([k]) => k)
		.sort();
}

/**
 * The group headings and each section's own label and help (`settings_<section>_label`, three
 * parts) are common: the navigation and the Overview need them without any section's fields. The
 * rest belong to the section named after `settings_`.
 */
export function unitOf(key: string): string {
	const parts = key.split('_');
	if (key.startsWith('settings_group_')) return COMMON;
	if (parts.length === 3 && (parts[2] === 'label' || parts[2] === 'help')) return COMMON;
	return parts[1]!;
}

/** The keys of each unit, units in name order. */
export function splitUnits(keys: string[]): Map<string, string[]> {
	const units = new Map<string, string[]>();
	for (const k of keys) {
		const unit = unitOf(k);
		(units.get(unit) ?? units.set(unit, []).get(unit)!).push(k);
	}
	return new Map([...units].sort(([a], [b]) => (a < b ? -1 : 1)));
}

const HEADER = '// Generated by message-map.gen.ts from ../messages/en.json; do not edit.';

/** `message-map.ts`: a loader per unit. */
export function renderIndex(units: string[]): string {
	const body = units.length
		? `{\n${units.map((u) => `\t${u}: () => import('./message-map/${u}')`).join(',\n')}\n}`
		: '{}';
	return [
		HEADER,
		`export const COMMON_UNIT = '${COMMON}';`,
		'export type MessageUnit = { MESSAGES: Record<string, () => string> };',
		'',
		`export const LOADERS: Record<string, () => Promise<MessageUnit>> = ${body};`,
		''
	].join('\n');
}

/** Prettier's print width and tab width (`.prettierrc`): a property wider than this wraps. */
const PRINT_WIDTH = 100;
const TAB_WIDTH = 2;

function property(key: string, last: boolean): string {
	const comma = last ? '' : ',';
	const flat = `\t${key}: m.${key}${comma}`;
	return flat.length - 1 + TAB_WIDTH > PRINT_WIDTH ? `\t${key}:\n\t\tm.${key}${comma}` : flat;
}

/** `message-map/<unit>.ts`: the unit's messages, each read statically. */
export function renderUnit(keys: string[]): string {
	const body = keys.map((k, i) => property(k, i === keys.length - 1)).join('\n');
	return [
		HEADER,
		"import { m } from '$lib/paraglide/messages.js';",
		'',
		`export const MESSAGES: Record<string, () => string> = {\n${body}\n};`,
		''
	].join('\n');
}

/** Every generated file's text: path → content. */
export function renderAll(enText: string): Map<string, string> {
	const units = splitUnits(messageKeys(enText));
	const files = new Map<string, string>([[MAP_FILE, renderIndex([...units.keys()])]]);
	for (const [unit, keys] of units) files.set(join(MAP_DIR, `${unit}.ts`), renderUnit(keys));
	return files;
}

if (process.argv[1] === import.meta.filename) {
	const files = renderAll(readFileSync(EN_FILE, 'utf8'));
	mkdirSync(MAP_DIR, { recursive: true });
	for (const stale of readdirSync(MAP_DIR)) rmSync(join(MAP_DIR, stale));
	for (const [file, text] of files) writeFileSync(file, text);
}
