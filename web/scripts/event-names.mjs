// Writes src/lib/features/settings/logging/event-names.ts from the server's event catalogue
// (crates/lodestar/src/settings/golden/logs_catalog.txt), in catalogue order:
//
//   npm run event-names
//
// Each event id maps to its plain name and help messages, `settings_logging_ev_<id>_n` and `_h`
// (en and zh, in logging/messages/). `scripts/event-names.test.ts` fails when the file is stale,
// and the messages themselves are checked against the catalogue by logging/event-labels.test.ts.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const CATALOG = join(ROOT, '../crates/lodestar/src/settings/golden/logs_catalog.txt');
export const OUTPUT = join(ROOT, 'src/lib/features/settings/logging/event-names.ts');

/** Event ids in catalogue order. The golden file is a status line, then the JSON body. */
export function eventIds(golden) {
	const body = golden.slice(golden.indexOf('\n') + 1).split('\n')[0];
	return JSON.parse(body).events.map((e) => e.id);
}

/** The file's text, formatted as `npm run format` would leave it. */
export async function render(golden) {
	const entries = eventIds(golden).map((id) => {
		const k = `settings_logging_ev_${id.replaceAll('.', '_')}`;
		return `\t'${id}': [m.${k}_n, m.${k}_h],`;
	});
	const source = [
		'// Generated by scripts/event-names.mjs from the event list in the logs catalogue; one plain',
		'// name and one line of help per event id (en and zh in messages/). Loaded after the event',
		'// list shows, as its own chunk. Do not edit.',
		"import { m } from '$lib/paraglide/messages.js';",
		'',
		'export const NAMES: Record<string, [name: () => string, help: () => string]> = {',
		...entries,
		'};',
		''
	].join('\n');
	const config = (await prettier.resolveConfig(OUTPUT)) ?? {};
	return prettier.format(source, { ...config, filepath: OUTPUT });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	writeFileSync(OUTPUT, await render(readFileSync(CATALOG, 'utf8')));
	console.log(`event-names: wrote ${OUTPUT}`);
}
