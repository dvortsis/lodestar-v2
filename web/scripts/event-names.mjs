// Writes src/lib/features/settings/logging/event-names/<component>.ts (one chunk per component) and
// the loader map event-names.ts from the server's event catalogue
// (crates/lodestar/src/settings/golden/logs_catalog.txt), in catalogue order:
//
//   npm run event-names
//
// Each event id maps to its plain name and help messages, `settings_logging_ev_<id>_n` and `_h`
// (en and zh, in logging/messages/). `scripts/event-names.test.ts` fails when the file is stale,
// and the messages themselves are checked against the catalogue by logging/event-labels.test.ts.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const CATALOG = join(ROOT, '../crates/lodestar/src/settings/golden/logs_catalog.txt');
export const OUTPUT = join(ROOT, 'src/lib/features/settings/logging/event-names.ts');
export const DIR = join(ROOT, 'src/lib/features/settings/logging/event-names');

/** Event ids grouped by component, each group in catalogue order (components in first-seen order). */
export function eventsByComponent(golden) {
	const body = golden.slice(golden.indexOf('\n') + 1).split('\n')[0];
	const groups = new Map();
	for (const e of JSON.parse(body).events) {
		if (!groups.has(e.component)) groups.set(e.component, []);
		groups.get(e.component).push(e.id);
	}
	return groups;
}

/** Component ids in catalogue order. */
export const componentIds = (golden) => [...eventsByComponent(golden).keys()];

const key = (id) => `settings_logging_ev_${id.replaceAll('.', '_')}`;

async function format(source, filepath) {
	const config = (await prettier.resolveConfig(filepath)) ?? {};
	return prettier.format(source, { ...config, filepath });
}

/** The output files as { absolute path: text }, formatted as `npm run format` would leave them. */
export async function render(golden) {
	const out = {};
	const groups = eventsByComponent(golden);
	for (const [component, ids] of groups) {
		const file = join(DIR, `${component}.ts`);
		const entries = ids.map((id) => `\t'${id}': [m.${key(id)}_n, m.${key(id)}_h],`);
		out[file] = await format(
			[
				`// Generated by scripts/event-names.mjs from the logs catalogue: the plain name and help of`,
				`// each \`${component}\` event (en and zh in messages/). Its own chunk, loaded when one of these`,
				'// events is shown. Do not edit.',
				"import { m } from '$lib/paraglide/messages.js';",
				'',
				'export const NAMES: Record<string, [name: () => string, help: () => string]> = {',
				...entries,
				'};',
				''
			].join('\n'),
			file
		);
	}
	out[OUTPUT] = await format(
		[
			'// Generated by scripts/event-names.mjs from the logs catalogue: one on-demand chunk of event',
			'// names per component, so a new event grows one small chunk. Do not edit.',
			'export type EventNames = Record<string, [name: () => string, help: () => string]>;',
			'',
			'export const CHUNKS: Record<string, () => Promise<{ NAMES: EventNames }>> = {',
			...[...groups.keys()].map((c) => `\t${c}: () => import('./event-names/${c}'),`),
			'};',
			''
		].join('\n'),
		OUTPUT
	);
	return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	const files = await render(readFileSync(CATALOG, 'utf8'));
	mkdirSync(DIR, { recursive: true });
	// A component the catalogue no longer has loses its chunk.
	for (const f of readdirSync(DIR)) if (!(join(DIR, f) in files)) rmSync(join(DIR, f));
	for (const [file, text] of Object.entries(files)) writeFileSync(file, text);
	console.log(`event-names: wrote ${Object.keys(files).length} files`);
}
